g.set_titles("Week {col_name}")
g.fig.suptitle("MTTR Comparison: ESB vs. ETL Teams by Sub-Platform (Weekly)", y=1.02, fontsize=16)

# Adjust the layout to prevent titles/labels from overlapping
plt.tight_layout(rect=[0, 0, 1, 0.98]) # Leaves space for the suptitle

# Save the plot to an image file
plt.savefig('mttr_comparison_plot_with_labels_highlighted.png')
plt.show()

